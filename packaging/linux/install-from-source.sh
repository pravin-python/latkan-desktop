#!/usr/bin/env bash
# Install Latkan from this source checkout for the current user (Ubuntu / Debian and derivatives).
#
# Usage: bash packaging/linux/install-from-source.sh [--autostart] [--no-apt] [--python PYTHON] [--uninstall]
#
#   1. apt: python3-venv and the X11/xcb runtime libraries Qt 6 needs (uses sudo; skip with --no-apt)
#   2. creates ~/.local/share/latkan/venv and pip-installs Latkan into it
#   3. writes the ~/.local/bin/latkan launcher, a menu entry and an icon
#   4. --autostart: start Latkan at login (the same file the in-app "Start at login" toggle manages)
#
# Settings in ~/.config/latkan are never touched, not even by --uninstall.
# Run it as your normal user, not with sudo - it asks for sudo only for apt.
set -euo pipefail

die() { echo "error: $*" >&2; exit 1; }
info() { echo "==> $*"; }
note() { echo "    $*"; }

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
PREFIX="$DATA_HOME/latkan"
VENV="$PREFIX/venv"
BIN_DIR="$HOME/.local/bin"
LAUNCHER="$BIN_DIR/latkan"
APPS_DIR="$DATA_HOME/applications"
DESKTOP_FILE="$APPS_DIR/latkan.desktop"
ICON_THEME_DIR="$DATA_HOME/icons/hicolor"
ICON_FILE="$ICON_THEME_DIR/256x256/apps/latkan.png"
AUTOSTART_FILE="$CONFIG_HOME/autostart/latkan.desktop"
MARKER="# Generated by latkan packaging/linux/install-from-source.sh"

APT_PACKAGES=(
    python3-venv
    # Qt 6 xcb platform plugin runtime (Qt >= 6.5 refuses to start without libxcb-cursor0)
    libxcb-cursor0 libxkbcommon-x11-0 libegl1 libgl1 libdbus-1-3 libfontconfig1
    libxcb-icccm4 libxcb-image0 libxcb-keysyms1 libxcb-randr0 libxcb-render-util0
    libxcb-shape0 libxcb-xfixes0 libxcb-xinerama0 libxcb-xkb1
)

AUTOSTART=0
USE_APT=1
UNINSTALL=0
PYTHON="python3"

usage() {
    sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    exit "${1:-0}"
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --autostart) AUTOSTART=1 ;;
        --no-apt) USE_APT=0 ;;
        --uninstall) UNINSTALL=1 ;;
        --python) [[ $# -ge 2 ]] || die "--python needs an argument"; PYTHON="$2"; shift ;;
        --python=*) PYTHON="${1#*=}" ;;
        -h|--help) usage 0 ;;
        *) echo "unknown option: $1" >&2; usage 2 ;;
    esac
    shift
done

if [[ "$(id -u)" -eq 0 ]]; then
    die "run this script as your normal user (without sudo); it calls sudo itself for apt"
fi

# The generated files embed these paths; refuse characters that would need multi-level escaping.
for path in "$VENV" "$LAUNCHER"; do
    case "$path" in
        *[\"\`\$\\]*) die "unsupported character (quote, backtick, dollar or backslash) in path: $path" ;;
    esac
done

# Desktop Entry "Exec" quoting: plain paths stay bare, anything with spaces etc. is double-quoted.
desktop_arg() {
    local arg="$1"
    if [[ "$arg" =~ ^[A-Za-z0-9_./+:@%-]+$ ]]; then
        printf '%s' "$arg"
    else
        printf '"%s"' "$arg"
    fi
}

# POSIX-shell single quoting for the generated launcher.
sh_quote() {
    printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}

refresh_desktop_caches() {
    if command -v update-desktop-database >/dev/null 2>&1; then
        update-desktop-database -q "$APPS_DIR" 2>/dev/null || true
    fi
    if command -v gtk-update-icon-cache >/dev/null 2>&1 && [[ -d "$ICON_THEME_DIR" ]]; then
        gtk-update-icon-cache -q -f -t "$ICON_THEME_DIR" 2>/dev/null || true
    fi
}

# Remove a file only when it was generated by this installer / points at our venv.
remove_ours() {
    local file="$1"
    if [[ -f "$file" ]] && grep -qF -e "$MARKER" -e "$VENV" "$file"; then
        rm -f "$file"
        note "removed $file"
    fi
}

# ------------------------------------------------------------------------------------- uninstall

if [[ "$UNINSTALL" -eq 1 ]]; then
    info "Uninstalling Latkan (settings in $CONFIG_HOME/latkan are kept)"
    pkill -u "$(id -u)" -f "$VENV/bin/" 2>/dev/null || true
    remove_ours "$LAUNCHER"
    remove_ours "$DESKTOP_FILE"
    remove_ours "$AUTOSTART_FILE"
    if [[ -f "$ICON_FILE" ]]; then rm -f "$ICON_FILE"; note "removed $ICON_FILE"; fi
    if [[ -d "$VENV" ]]; then rm -rf "$VENV"; note "removed $VENV"; fi
    rmdir "$PREFIX" 2>/dev/null || true
    refresh_desktop_caches
    info "Done."
    exit 0
fi

# ---------------------------------------------------------------------------------------- checks

[[ -f "$ROOT/pyproject.toml" && -d "$ROOT/src/latkan" ]] || die "run this from a Latkan source checkout"
command -v "$PYTHON" >/dev/null 2>&1 || die "$PYTHON not found (install python3 >= 3.10 or pass --python)"
"$PYTHON" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 10) else 1)' \
    || die "Latkan needs Python >= 3.10; $("$PYTHON" -V 2>&1) found. Pass --python /path/to/python3.10+"
PY_MINOR="$("$PYTHON" -c 'import sys; print(f"{sys.version_info[0]}.{sys.version_info[1]}")')"

# ------------------------------------------------------------------------------------ apt packages

if [[ "$USE_APT" -eq 1 ]]; then
    if command -v apt-get >/dev/null 2>&1; then
        packages=("${APT_PACKAGES[@]}")
        # a non-default interpreter (e.g. python3.12 on 22.04) has its own -venv package
        if apt-cache show "python$PY_MINOR-venv" >/dev/null 2>&1; then
            packages+=("python$PY_MINOR-venv")
        fi
        info "Installing system packages (sudo): ${packages[*]}"
        command -v sudo >/dev/null 2>&1 || die "sudo not found - install the packages above as root, then use --no-apt"
        sudo apt-get update -qq
        sudo apt-get install -y --no-install-recommends "${packages[@]}"
    else
        info "apt-get not found - skipping system packages. Make sure these (or your distro's equivalents) are installed:"
        note "${APT_PACKAGES[*]}"
    fi
fi

"$PYTHON" -c 'import ensurepip, venv' 2>/dev/null \
    || die "the venv module is missing: sudo apt install python3-venv (or python$PY_MINOR-venv)"

# ------------------------------------------------------------------------------ venv + pip install

info "Creating virtual environment in $VENV"
mkdir -p "$PREFIX"
"$PYTHON" -m venv --clear "$VENV"
"$VENV/bin/python" -m pip install --quiet --disable-pip-version-check --upgrade pip
info "Installing Latkan from $ROOT (downloads PySide6, ~100 MB, on first install)"
"$VENV/bin/python" -m pip install --disable-pip-version-check "$ROOT"
"$VENV/bin/python" -c 'import latkan; print("    installed latkan", latkan.__version__)'

# -------------------------------------------------------------------------------------- launcher

info "Writing launcher $LAUNCHER"
mkdir -p "$BIN_DIR"
{
    echo "#!/bin/sh"
    echo "$MARKER"
    echo "exec $(sh_quote "$VENV/bin/latkan") \"\$@\""
} > "$LAUNCHER.tmp"
chmod 0755 "$LAUNCHER.tmp"
mv -f "$LAUNCHER.tmp" "$LAUNCHER"

# ------------------------------------------------------------------------------------------- icon

info "Installing icon $ICON_FILE"
mkdir -p "$(dirname "$ICON_FILE")"
if [[ -f "$ROOT/assets/icon-256.png" ]]; then
    install -m 0644 "$ROOT/assets/icon-256.png" "$ICON_FILE"
else
    icon_tmp="$(mktemp -d)"
    trap 'rm -rf "$icon_tmp"' EXIT
    QT_QPA_PLATFORM=offscreen "$VENV/bin/python" "$ROOT/scripts/make_icons.py" --png-only --quiet --out "$icon_tmp" \
        || die "icon generation failed"
    install -m 0644 "$icon_tmp/icon-256.png" "$ICON_FILE"
fi

# ---------------------------------------------------------------------------------- menu entry

info "Writing menu entry $DESKTOP_FILE"
mkdir -p "$APPS_DIR"
exec_value="$(desktop_arg "$LAUNCHER")"
{
    while IFS= read -r line || [[ -n "$line" ]]; do
        if [[ "$line" == Exec=* ]]; then
            printf 'Exec=%s\n' "$exec_value"
        else
            printf '%s\n' "$line"
        fi
    done < "$ROOT/packaging/linux/latkan.desktop"
    echo "$MARKER"
} > "$DESKTOP_FILE.tmp"
mv -f "$DESKTOP_FILE.tmp" "$DESKTOP_FILE"
refresh_desktop_caches

# ----------------------------------------------------------------------------------- autostart

if [[ "$AUTOSTART" -eq 1 ]]; then
    info "Enabling start at login: $AUTOSTART_FILE"
    mkdir -p "$(dirname "$AUTOSTART_FILE")"
    # Same content the app writes itself (latkan.platform.linux), so the tray toggle recognises it.
    cat > "$AUTOSTART_FILE.tmp" <<EOF
[Desktop Entry]
Type=Application
Name=Latkan
Comment=Charms that hang from the top of your screen
Exec=$(desktop_arg "$VENV/bin/python") -m latkan
Icon=latkan
Terminal=false
StartupNotify=false
X-GNOME-Autostart-enabled=true
EOF
    mv -f "$AUTOSTART_FILE.tmp" "$AUTOSTART_FILE"
fi

# ---------------------------------------------------------------------------------------- done

info "Latkan installed. Start it from your applications menu or run: latkan"
case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) note "note: $BIN_DIR is not on your PATH; run $LAUNCHER or add it to PATH (then log in again)" ;;
esac
if [[ "${XDG_CURRENT_DESKTOP:-}" == *GNOME* ]] && ! gnome-extensions list 2>/dev/null | grep -qi appindicator; then
    note "note: GNOME shows tray icons only with the AppIndicator extension"
    note "      (sudo apt install gnome-shell-extension-appindicator, then log out and in)."
    note "      Without it, right-click any charm for the menu."
fi
if [[ -n "${WAYLAND_DISPLAY:-}" ]]; then
    note "note: on Wayland Latkan runs through XWayland automatically (needed for always-on-top overlays)."
fi
note "uninstall: bash $0 --uninstall"
